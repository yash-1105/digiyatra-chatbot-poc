def digits(text: str) -> str:
    return ''.join(str(unicodedata.digit(c)) if c.isdecimal() else c for c in text)


def concepts(text: str, *, hinglish: bool = True) -> str:
    text = unicodedata.normalize("NFKC", text).replace("’", "'")
    text = "".join(str(unicodedata.digit(c)) if c.isdecimal() else c for c in text)
    terms = TERMS | (HINGLISH if hinglish else {})
    pattern = (
        r"(?<![\w\u0900-\u097f])("
        + "|".join(re.escape(k) for k in sorted(terms, key=len, reverse=True))
        + r")(?![\w\u0900-\u097f])"
    )
    return re.sub(pattern, lambda m: terms[m.group(0).lower()], text, flags=re.I)


def normalize_question(text: str) -> str:
    q = concepts(text).lower()
    q = re.sub(
        r"\b(otp|nfc|qr(?: code)?|android|facial recognition)\s+(?:kya (?:hota )?hai|क्या (?:होता )?है)\s*[?.।!]*$",
        r"what is \1?",
        q,
    )
    q = re.sub(r"\b(otp|nfc|qr|android)\s+क्या\s+है", r"what is \1", q)
    if re.search(r"\baadhaar\b.{0,15}\bnot\b\s*(?:hai|है)?", q):
        q += " without aadhaar"
    # Hindi questions often omit an English verb: explicit platform concepts suffice.
    if re.search(r"\b(android|ios|iphone|samsung)\b", q) and not re.match(r"what is android", q):
        q += "" if "app available" in q else " app available"
    if re.search(r"\b(where|how)\b", q) and re.search(
        r"\b(upload|scan|register|registration|download|delete|add|link)\b", q
    ):
        q = q if q.startswith("how ") else "how " + q
    return q
